CREATE OR REPLACE VIEW financial_account_balances AS
SELECT ca.store_id, ca.id, ca.code, ca.name, ca.account_type,
       COALESCE(SUM(jl.debit - jl.credit), 0)::numeric(14,2) AS balance
FROM chart_of_accounts ca
LEFT JOIN journal_lines jl ON jl.account_id = ca.id
GROUP BY ca.store_id, ca.id, ca.code, ca.name, ca.account_type;
