DROP POLICY IF EXISTS tenant_self_access ON tenants;
CREATE POLICY tenant_self_access ON tenants FOR SELECT USING (can_access_tenant(id));
DROP POLICY IF EXISTS membership_self_access ON tenant_memberships;
CREATE POLICY membership_self_access ON tenant_memberships FOR SELECT USING (user_id = auth.uid() OR can_access_tenant(tenant_id));
DROP POLICY IF EXISTS entities_tenant_access ON entities;
CREATE POLICY entities_tenant_access ON entities USING (can_access_tenant(tenant_id)) WITH CHECK (can_access_tenant(tenant_id));
DROP POLICY IF EXISTS inventory_stock_warehouse_access ON inventory_stock;
CREATE POLICY inventory_stock_warehouse_access ON inventory_stock USING (can_access_warehouse(tenant_id, warehouse_id)) WITH CHECK (can_access_warehouse(tenant_id, warehouse_id));
DROP POLICY IF EXISTS stock_ledger_warehouse_access ON stock_ledger;
CREATE POLICY stock_ledger_warehouse_access ON stock_ledger USING (can_access_warehouse(tenant_id, warehouse_id)) WITH CHECK (can_access_warehouse(tenant_id, warehouse_id));
DROP POLICY IF EXISTS invoices_tenant_access ON invoices;
CREATE POLICY invoices_tenant_access ON invoices USING (can_access_tenant(tenant_id)) WITH CHECK (can_access_tenant(tenant_id));
DROP POLICY IF EXISTS invoice_lines_tenant_access ON invoice_lines;
CREATE POLICY invoice_lines_tenant_access ON invoice_lines USING (can_access_tenant(tenant_id)) WITH CHECK (can_access_tenant(tenant_id));
DROP POLICY IF EXISTS sales_tenant_access ON sales;
CREATE POLICY sales_tenant_access ON sales USING (can_access_tenant(tenant_id)) WITH CHECK (can_access_tenant(tenant_id));
